#!/usr/bin/env python3
"""Generate/check the embedded copy of the authoritative evidence schemas."""
import argparse
import json
from pathlib import Path

repository = Path(__file__).resolve().parents[2]
schemas = repository / "include/devSystems/devAgenticWorkflow/schemas/v1"
header = schemas / "AgenticSchemaData.hpp"
rows = []

SUPPORTED_KEYWORDS = {
    "$schema", "$id", "$ref", "$defs", "title", "description", "default", "examples",
    "type", "properties", "required", "additionalProperties", "const", "enum", "not",
    "anyOf", "oneOf", "allOf", "items", "minItems", "maxItems", "uniqueItems",
    "minimum", "maximum", "exclusiveMinimum", "minLength", "maxLength", "pattern", "format",
}


def validate_schema_contract(document, root=None):
    """Fail CI when a schema claims a validation keyword the runtime does not implement."""
    if isinstance(document, bool):
        return
    if not isinstance(document, dict):
        raise SystemExit("schema nodes must be objects or boolean schemas")
    if root is None:
        root = document
    unknown = set(document) - SUPPORTED_KEYWORDS
    if unknown:
        raise SystemExit(f"runtime does not implement schema keywords: {sorted(unknown)}")
    if "$ref" in document:
        reference = document["$ref"]
        if reference != "#" and not reference.startswith("#/"):
            raise SystemExit(f"external schema references are not supported: {reference}")
        selected = root
        if reference != "#":
            for key in reference[2:].split("/"):
                key = key.replace("~1", "/").replace("~0", "~")
                if not isinstance(selected, dict) or key not in selected:
                    raise SystemExit(f"unresolved local schema reference: {reference}")
                selected = selected[key]
    if "type" in document:
        types = document["type"] if isinstance(document["type"], list) else [document["type"]]
        if not types or not set(types) <= {"object", "array", "string", "number", "integer", "boolean", "null"}:
            raise SystemExit("unsupported JSON Schema type")
    if document.get("format") not in {None, "date-time"}:
        raise SystemExit("runtime only implements the date-time format")
    for keyword in ["properties", "$defs"]:
        for child in document.get(keyword, {}).values():
            validate_schema_contract(child, root)
    for keyword in ["items", "additionalProperties", "not"]:
        if keyword in document:
            validate_schema_contract(document[keyword], root)
    for keyword in ["anyOf", "oneOf", "allOf"]:
        if keyword in document:
            if not isinstance(document[keyword], list) or not document[keyword]:
                raise SystemExit(f"{keyword} must contain at least one schema")
            for child in document[keyword]:
                validate_schema_contract(child, root)


for schema in sorted(schemas.glob("*.schema.json")):
    document = json.loads(schema.read_text(encoding="utf-8"))
    validate_schema_contract(document)
    encoded = json.dumps(document, separators=(",", ":"), sort_keys=True)
    rows.append(f'    std::pair<std::string_view, std::string_view>{{"{document["title"]}", R"schema({encoded})schema"}}')
content = "// Generated by tools/flowui-agent/check_schemas.py; edit the JSON Schemas.\n#pragma once\n#include <array>\n#include <string_view>\n#include <utility>\nnamespace FlowUi::devSystems::agentic::detail {\ninline constexpr std::array schema_documents{\n" + ",\n".join(rows) + "\n};\n}\n"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
arguments = parser.parse_args()
if arguments.check:
    if not header.exists() or header.read_text(encoding="utf-8") != content:
        raise SystemExit("embedded agentic schemas are stale; run tools/flowui-agent/check_schemas.py")
else:
    header.write_text(content, encoding="utf-8")
