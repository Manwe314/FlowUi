/**
 * @brief Baked glyph metrics and atlas coordinates.
 *
 * GlyphData is loaded from baked font data or generated by runtime font baking.
 * It is consumed by FlowUi text layout and rendering code.
 */
struct GlyphData {
	/** @brief Unicode codepoint represented by the glyph. */
	uint32_t codepoint = 0;
	/** @brief Source atlas image index. */
	uint32_t sourceImageIndex = 0;
	/** @brief Left glyph plane bound in font design space. */
	float planeLeft = 0.0f;
	/** @brief Bottom glyph plane bound in font design space. */
	float planeBottom = 0.0f;
	/** @brief Right glyph plane bound in font design space. */
	float planeRight = 0.0f;
	/** @brief Top glyph plane bound in font design space. */
	float planeTop = 0.0f;
	/** @brief Left glyph atlas bound in source atlas pixels. */
	float imageLeft = 0.0f;
	/** @brief Bottom glyph atlas bound in source atlas pixels. */
	float imageBottom = 0.0f;
	/** @brief Right glyph atlas bound in source atlas pixels. */
	float imageRight = 0.0f;
	/** @brief Top glyph atlas bound in source atlas pixels. */
	float imageTop = 0.0f;
	/** @brief Horizontal glyph advance. */
	float advanceX = 0.0f;
	/** @brief Vertical glyph advance. */
	float advanceY = 0.0f;
};

/**
 * @brief One baked variant of a font face.
 *
 * A variant stores metrics, glyphs, and kerning for one loaded font face
 * variant. FontFaceData selects one variant as the default for layout.
 */
struct FontVariantData {
	/** @brief Source font variant flags from the loaded font data. */
	uint32_t flags = 0;
	/** @brief Font weight. */
	uint32_t weight = 0;
	/** @brief Glyph index used as fallback. */
	uint32_t fallbackGlyphIndex = 0;
	/** @brief Baked font size in pixels. */
	float fontSizePx = 0.0f;
	/** @brief MSDF distance range. */
	float distanceRange = 0.0f;
	/** @brief EM size from font metadata. */
	float emSize = 0.0f;
	/** @brief Font ascender metric. */
	float ascender = 0.0f;
	/** @brief Font descender metric. */
	float descender = 0.0f;
	/** @brief Font line height metric. */
	float lineHeight = 0.0f;
	/** @brief Underline Y metric. */
	float underlineY = 0.0f;
	/** @brief Underline thickness metric. */
	float underlineThickness = 0.0f;
	/** @brief MSDF distance range midpoint. */
	float distanceRangeMiddle = 0.0f;
	/** @brief Variant name. */
	std::string name;
	/** @brief Raw metadata associated with the variant. */
	std::string metadata;
	/** @brief Glyph table. */
	std::vector<GlyphData> glyphs;
	/** @brief Unicode codepoint to glyph index lookup. */
	std::unordered_map<uint32_t, uint32_t> unicodeToGlyphIndex;
	/** @brief Kerning pair lookup table. */
	std::unordered_map<uint64_t, float> kerningPairs;

	/** @brief Pack leftCodepoint in the high 32 bits and rightCodepoint in the low 32 bits.
	 * @return Lookup key used by kerningPairs. */
	[[nodiscard]] static constexpr uint64_t kerningKey(uint32_t leftCodepoint,
													   uint32_t rightCodepoint) noexcept {
		return (static_cast<uint64_t>(leftCodepoint) << 32u) |
			   static_cast<uint64_t>(rightCodepoint);
	}

	/** @brief Return the stored horizontal kerning adjustment, or zero when the pair is absent.
	 * @param leftCodepoint Unicode codepoint preceding rightCodepoint.
	 * @param rightCodepoint Following Unicode codepoint.
	 * @return Adjustment in the variant's font metric units. */
	[[nodiscard]] float kerningAdvance(uint32_t leftCodepoint,
									   uint32_t rightCodepoint) const noexcept {
		const auto it = kerningPairs.find(kerningKey(leftCodepoint, rightCodepoint));
		return (it != kerningPairs.end()) ? it->second : 0.0f;
	}
};

/**
 * @brief Loaded font face and its baked variants.
 *
 * FontFaceData is returned by FlowUi::FontManager::getFontById() for applications that
 * need direct access to loaded font metrics or atlas placement data.
 */
struct FontFaceData {
	/** @brief Borrow the selected variant; nullptr means the variant list or index is invalid.
	 * The pointer is invalidated by mutation or destruction of this face's variants. */
	[[nodiscard]] const FontVariantData* defaultVariant() const noexcept {
		if (variants.empty() || defaultVariantIndex >= variants.size()) {
			return nullptr;
		}
		return &variants[defaultVariantIndex];
	}
	/** @brief Source file path. */
	std::filesystem::path sourcePath;
	/** @brief Font face name. */
	std::string name;
	/** @brief Raw metadata associated with the face. */
	std::string metadata;
	/** @brief Baked variants for this face. */
	std::vector<FontVariantData> variants;
	/** @brief FlowUi font id. */
	FontId id = 0;
	/** @brief Atlas layer used by this font face. */
	uint32_t atlasLayer = 0;
	/** @brief Atlas width in pixels. */
	uint32_t atlasWidth = 0;
	/** @brief Atlas height in pixels. */
	uint32_t atlasHeight = 0;
	/** @brief X offset where this face's source atlas was placed inside the atlas page. */
	uint32_t sourceAtlasX = 0;
	/** @brief Y offset where this face's source atlas was placed inside the atlas page. */
	uint32_t sourceAtlasY = 0;
	/** @brief Source atlas width before placement into the atlas page. */
	uint32_t sourceAtlasWidth = 0;
	/** @brief Source atlas height before placement into the atlas page. */
	uint32_t sourceAtlasHeight = 0;
	/** @brief Source atlas image type from the loaded font data. */
	uint32_t imageType = 0;
	/** @brief Default variant index. */
	uint32_t defaultVariantIndex = 0;
};

