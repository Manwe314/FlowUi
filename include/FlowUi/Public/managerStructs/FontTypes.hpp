namespace FlowUi {

/** Manager-assigned font-face identity used by Clay text declarations; zero is the startup fallback face. */
using FontId = uint16_t;
/** Manager-assigned font-family identity; zero is the startup fallback family. */
using FontFamilyId = uint32_t;

/** Requested face style used with weight for family resolution. */
enum class FontStyle : uint8_t {
	/** Upright/normal face. */
	Normal,
	/** Italic face. */
	Italic,
};

/**
 * Owned description of a baked .arfont face or a runtime-baked source font. Runtime baking requires
 * the corresponding build feature.
 */
struct FontFaceCreateInfo {
	/** Source font asset path resolved by the resource configuration. */
	std::filesystem::path path{};
	/** Requested bake size in pixels for runtime source fonts; baked assets retain their authored metrics. */
	float pixelSize = 18.0f;
	/** Weight used to select this face, commonly 400 for regular and 700 for bold. */
	uint32_t weight = 400;
	/** Style used to select this face. */
	FontStyle style = FontStyle::Normal;
	/** Optional explicit face name; empty lets loading derive one. */
	std::string name{};
};

/** Owned family name and face list passed to FontManager during registration. */
struct FontFamilyCreateInfo {
	/** Unique family registration name. */
	std::string name = "Default";
	/** Owned candidate faces, typically varying by weight and style. */
	std::vector<FontFaceCreateInfo> faces{
		FontFaceCreateInfo{
			.path = "assets/fonts/Inter.arfont",
			.pixelSize = 18.0f,
			.weight = 400,
			.style = FontStyle::Normal,
		},
	};
};

} // namespace FlowUi

