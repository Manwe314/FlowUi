/** Recognized IDs only; historic aggregate estimates are deliberately unsupported. */
[[nodiscard]] constexpr const InitialCapacityDefinition*
find_initial_capacity(MemoryCapacityTargetId id) noexcept {
	for (const auto& definition : initial_capacity_definitions)
		if (definition.id() == id)
			return &definition;
	return nullptr;
}
[[nodiscard]] constexpr bool valid_initial_capacity(const InitialCapacityDefinition& definition,
													uint64_t value) noexcept {
	return value == 0 || (value <= definition.maximum && value % definition.alignment == 0);
}
/** Fixed startup dispatch table; no settings scans in frames or insertions. */
struct InitialMemoryCapacities {
	std::array<uint64_t, static_cast<size_t>(InitialCapacityTarget::count)> values{};
	[[nodiscard]] constexpr uint64_t get(InitialCapacityTarget target) const noexcept {
		const auto index = static_cast<size_t>(target);
		return values[index] == 0 ? initial_capacity_definitions[index].default_value
								  : values[index];
	}
};
